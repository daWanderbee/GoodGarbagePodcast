// Rebuilds src/lib/guest-portraits.ts from whatever is in public/images/guests/.
// Run after adding or removing a portrait.
//   node scripts/build-guest-portraits.mjs
import { readdirSync, writeFileSync } from "node:fs";

const ids = readdirSync("public/images/guests")
  .filter((f) => f.endsWith(".jpg"))
  .map((f) => f.replace(/\.jpg$/, ""))
  .sort();

writeFileSync(
  "src/lib/guest-portraits.ts",
  `// GENERATED by scripts/build-guest-portraits.mjs — do not hand-edit.
// YouTube video ids with a verified guest portrait at public/images/guests/<id>.jpg,
// cropped from that episode's thumbnail.
//
// The show has used several thumbnail templates and the host is not always on the same
// side, so every crop was checked by eye against a contact sheet before shipping.
// Episodes whose thumbnail is a raw video-call grid are excluded — their layout varies,
// and a bad guess would put the host's face under a guest's name.
export const GUEST_PORTRAITS = new Set<string>([
${ids.map((i) => `  ${JSON.stringify(i)},`).join("\n")}
]);
`
);
console.log(`wrote src/lib/guest-portraits.ts — ${ids.length} portraits`);
