// Refreshes the committed episode snapshot in src/lib/episodes.ts from the RSS feed.
// The site reads the feed live (src/lib/get-episodes.ts); this snapshot is the fallback
// used when the feed is unreachable, so it is worth refreshing when episodes are added.
//
//   node --experimental-strip-types scripts/build-episodes.mjs [path-or-url] [--dry]
//
// Parsing lives in src/lib/feed.ts — shared with the runtime so the two cannot drift.
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { FEED_URL, parseFeed } from "../src/lib/feed.ts";
import { fetchChannelVideos } from "../src/lib/youtube.ts";

const arg = process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : FEED_URL;
const DRY = process.argv.includes("--dry");

const raw = existsSync(arg) ? readFileSync(arg, "utf8") : await (await fetch(arg)).text();
// Same live channel source the site uses, so the fallback snapshot is as complete as
// the runtime rather than stopping at the committed scrape.
const out = parseFeed(raw, await fetchChannelVideos());

if (DRY) {
  console.log(`${out.length} episodes from ${arg}`);
  console.log(`numbered: ${out.filter((e) => e.ep).length}, no guest: ${out.filter((e) => !e.guest).length}, no role: ${out.filter((e) => !e.role).length}`);
  console.log(`with a YouTube thumbnail: ${out.filter((e) => e.watch).length}`);
  console.log(`duplicate ids: ${out.length - new Set(out.map((e) => e.id)).size}`);
  const cats = {};
  for (const e of out) cats[e.category] = (cats[e.category] ?? 0) + 1;
  console.log("categories:", cats);
  for (const e of out.slice(0, 8)) {
    console.log(`  ${e.ep ? "#" + e.ep : "  —"} ${e.date} [${e.category}] ${e.guest || "??"} — ${e.role || "(no role)"}`);
  }
  process.exit(0);
}

const body = out.map((e) => "  " + JSON.stringify(e) + ",").join("\n");

writeFileSync(
  "src/lib/episodes.ts",
  `// GENERATED by scripts/build-episodes.mjs — do not hand-edit.
// Snapshot of ${FEED_URL}, used as the fallback when the live feed is unreachable.
// Guest, role and category are derived from the title and description by src/lib/feed.ts;
// everything else is verbatim from the feed.
import type { Episode } from "./feed.ts";

export type { Category, Episode } from "./feed.ts";
export { CATEGORIES } from "./feed.ts";

export const EPISODES: Episode[] = [
${body}
];
`
);
console.log(`wrote src/lib/episodes.ts — ${out.length} episodes`);
