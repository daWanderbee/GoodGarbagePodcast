// Applies scripts/portrait-rejects.txt: deletes the rejected crops from
// public/images/guests and regenerates src/lib/guest-portraits.ts from what is left.
//
//   node scripts/publish-portraits.mjs [--dry]
//
// The crops come from episode thumbnails, which are video-call stills, so about half of
// them are genuinely good headshots and about half are blurry, cut off, or have the teal
// title graphic across the face. A guests page is only as good as its worst face — one bad
// crop makes the whole grid look broken — so the weak ones are dropped rather than shipped.
//
// Dropping a crop only removes that guest's card. It never mislabels anyone, which is the
// failure mode that actually matters here.
import { readdirSync, readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";

const DIR = "public/images/guests";
const DRY = process.argv.includes("--dry");

const rejects = new Set(
  readFileSync("scripts/portrait-rejects.txt", "utf8")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"))
);

let removed = 0;
for (const file of rejects) {
  const path = `${DIR}/${file}`;
  if (!existsSync(path)) continue;
  if (!DRY) rmSync(path);
  removed++;
}

const kept = readdirSync(DIR)
  .filter((f) => f.endsWith(".jpg"))
  .map((f) => f.replace(/\.jpg$/, ""))
  .filter((id) => !rejects.has(`${id}.jpg`))
  .sort();

const out = `// GENERATED by scripts/publish-portraits.mjs — do not hand-edit.
// YouTube video ids with a guest portrait at public/images/guests/<id>.jpg, cropped from
// that episode's thumbnail by scripts/crop-portraits.ps1.
//
// Two filters stand between a thumbnail and this list. Every crop was classified by
// layout in scripts/portrait-templates.csv, because the show has used eight thumbnail
// layouts and the host is not always on the same side. Then every crop was reviewed by eye
// and the weak ones listed in scripts/portrait-rejects.txt — the source is video-call
// stills, so roughly half do not survive as headshots.
export const GUEST_PORTRAITS = new Set<string>([
${kept.map((i) => `  ${JSON.stringify(i)},`).join("\n")}
]);
`;

if (!DRY) writeFileSync("src/lib/guest-portraits.ts", out, "utf8");
console.error(`${DRY ? "[dry] " : ""}removed ${removed}, kept ${kept.length}`);
